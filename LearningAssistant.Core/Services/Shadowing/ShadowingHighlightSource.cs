using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using LearningAssistant.Models.Pdf;
using LearningAssistant.Models.Shadowing;

namespace LearningAssistant.Services.Shadowing
{
    /// <summary>整本跟读中的一条高亮句子及其所属页码。</summary>
    public sealed class ShadowingHighlightSentence
    {
        public int PageIndex { get; init; }
        public ShadowingSentence Sentence { get; init; } = new();

        /// <summary>来源高亮 ID；自动高亮重建后会变化，只作当前会话标签。</summary>
        public string? HighlightId { get; init; }

        /// <summary>稳定高亮锚点，供原声切片跨自动高亮重建找回。</summary>
        public string AnchorKey { get; init; } = string.Empty;

        /// <summary>一条高亮拆成多句时的句内序号；未拆分时为 0。</summary>
        public int PartIndex { get; init; }

        /// <summary>highlight / auto-highlight。</summary>
        public string TextSource { get; init; } = "highlight";

        public bool IsAutoGenerated { get; init; }
    }

    /// <summary>全书高亮整理结果：跟读句列表与被跳过的空文本高亮数量。</summary>
    public sealed class ShadowingHighlightPlan
    {
        public IReadOnlyList<ShadowingHighlightSentence> Sentences { get; init; } = Array.Empty<ShadowingHighlightSentence>();
        public int SkippedCount { get; init; }
    }

    /// <summary>
    /// 把全书高亮整理成稳定的跟读句：按页、纵向位置排序，过滤空文本，
    /// 并使用带前缀的高亮 ID，避免与按页分句产生的录音键冲突。
    /// </summary>
    public static class ShadowingHighlightSource
    {
        public const string SentenceIdPrefix = "hl:";

        private static readonly Regex TokenSeparator = new(@"[^\p{L}\p{Nd}]+", RegexOptions.Compiled);

        public static ShadowingHighlightPlan Build(
            IEnumerable<PdfHighlight>? highlights,
            bool splitIntoSentences = false)
        {
            var sentences = new List<ShadowingHighlightSentence>();
            if (highlights == null)
                return new ShadowingHighlightPlan { Sentences = sentences, SkippedCount = 0 };

            int skipped = 0;
            var seenIds = new HashSet<string>(StringComparer.Ordinal);
            var allHighlights = highlights.Where(h => h != null).ToList();
            var manualHighlights = allHighlights.Where(h => !h.IsAutoGenerated).ToList();

            // 自动高亮被手动高亮覆盖时跳过，并计入 skipped，避免整本列表出现重复句
            var usableHighlights = new List<PdfHighlight>(allHighlights.Count);
            foreach (var highlight in allHighlights)
            {
                if (IsDuplicateAutoHighlight(highlight, manualHighlights))
                {
                    skipped++;
                    continue;
                }

                usableHighlights.Add(highlight);
            }

            foreach (var highlight in usableHighlights
                         .OrderBy(h => h.PageIndex)
                         .ThenBy(h => h.NormalizedY)
                         .ThenBy(h => h.NormalizedX)
                         .ThenBy(h => h.CreatedAt)
                         .ThenBy(h => h.Id, StringComparer.Ordinal))
            {
                string text = NormalizeText(highlight.Text);
                if (text.Length == 0 || (highlight.IsAutoGenerated && CountLetters(text) < 2))
                {
                    skipped++;
                    continue;
                }

                var parts = splitIntoSentences ? SplitText(text) : new List<string> { text };
                if (parts.Count == 0)
                {
                    skipped++;
                    continue;
                }

                for (int partIndex = 0; partIndex < parts.Count; partIndex++)
                {
                    string partText = parts[partIndex];
                    string sentenceId = parts.Count == 1
                        ? SentenceIdPrefix + highlight.Id
                        : $"{SentenceIdPrefix}{highlight.Id}:{partIndex}";
                    if (!seenIds.Add(sentenceId))
                    {
                        skipped++;
                        continue;
                    }

                    sentences.Add(new ShadowingHighlightSentence
                    {
                        PageIndex = highlight.PageIndex,
                        Sentence = new ShadowingSentence
                        {
                            Id = sentenceId,
                            Index = sentences.Count,
                            StartOffset = 0,
                            Length = partText.Length,
                            Text = partText
                        },
                        HighlightId = highlight.Id,
                        AnchorKey = BuildAnchorKey(highlight, partIndex),
                        PartIndex = partIndex,
                        TextSource = highlight.IsAutoGenerated ? "auto-highlight" : "highlight",
                        IsAutoGenerated = highlight.IsAutoGenerated
                    });
                }
            }

            return new ShadowingHighlightPlan
            {
                Sentences = sentences,
                SkippedCount = skipped
            };
        }

        /// <summary>
        /// 把页面分句与同页高亮匹配成带锚点的跟读句。
        /// 文本完全一致优先；高亮包含该句时取最短包含项；否则按词重叠匹配。
        /// 页面句数与返回 cue 数始终一致，供原声对齐逐句推进。
        /// </summary>
        public static IReadOnlyList<ShadowingCue> BuildPageCues(
            IReadOnlyList<ShadowingSentence>? sentences,
            IEnumerable<PdfHighlight>? highlights,
            int pageIndex)
        {
            if (sentences == null || sentences.Count == 0)
                return Array.Empty<ShadowingCue>();

            var pageHighlights = (highlights ?? Array.Empty<PdfHighlight>())
                .Where(h => h != null && h.PageIndex == pageIndex)
                .Where(h => NormalizeText(h.Text).Length > 0)
                .ToList();

            // 与整本整理同一去重规则：自动高亮被手动高亮覆盖时跳过，
            // 否则自动高亮重建后页面句会匹配到不同坐标，锚点漂移导致切片找不到
            var manualHighlights = pageHighlights.Where(h => !h.IsAutoGenerated).ToList();
            if (manualHighlights.Count > 0)
            {
                pageHighlights = pageHighlights
                    .Where(h => !IsDuplicateAutoHighlight(h, manualHighlights))
                    .ToList();
            }

            var cues = new List<ShadowingCue>(sentences.Count);
            // 同文本序号：本页内该规范化文本第 k 次出现（按句序），与分句 ID 无关，抗重分句
            var textOrdinals = new Dictionary<string, int>(StringComparer.Ordinal);
            // 同一高亮覆盖多句时共用同一 base 锚点（取首句的同文本序号），组内序号保证 cue 唯一
            var highlightOrdinals = new Dictionary<string, int>(StringComparer.Ordinal);
            var groupOrdinals = new Dictionary<string, int>(StringComparer.Ordinal);
            foreach (var sentence in sentences)
            {
                string normalizedText = ShadowingAnchorKeys.NormalizeKey(sentence.Text);
                textOrdinals.TryGetValue(normalizedText, out int textOrdinal);
                textOrdinals[normalizedText] = textOrdinal + 1;

                var match = FindBestHighlight(sentence.Text, pageHighlights);
                string baseAnchor;
                string legacyAnchor;
                string? highlightId = null;
                string textSource = "page-text";
                if (match != null)
                {
                    highlightId = match.Id;
                    textSource = match.IsAutoGenerated ? "auto-highlight" : "highlight";
                    if (!highlightOrdinals.TryGetValue(match.Id, out int highlightOrdinal))
                    {
                        highlightOrdinal = textOrdinal;
                        highlightOrdinals[match.Id] = highlightOrdinal;
                    }

                    baseAnchor = ShadowingAnchorKeys.BuildHighlightV2(match, 0, highlightOrdinal);
                    legacyAnchor = ShadowingAnchorKeys.BuildCueV1(
                        ShadowingAnchorKeys.BuildHighlightV1(match, 0), sentence.Id);
                }
                else
                {
                    baseAnchor = ShadowingAnchorKeys.BuildPageTextV2(pageIndex, sentence.Text, textOrdinal);
                    legacyAnchor = $"txt:{pageIndex}:{sentence.Id}";
                }

                groupOrdinals.TryGetValue(baseAnchor, out int groupOrdinal);
                groupOrdinals[baseAnchor] = groupOrdinal + 1;

                cues.Add(new ShadowingCue
                {
                    PageIndex = pageIndex,
                    SentenceId = sentence.Id,
                    Text = sentence.Text,
                    HighlightId = highlightId,
                    AnchorKey = ShadowingAnchorKeys.BuildCueV2(baseAnchor, groupOrdinal),
                    LegacyAnchorKey = legacyAnchor,
                    TextSource = textSource
                });
            }

            return cues;
        }

        /// <summary>
        /// 生成跨自动高亮重建仍稳定的锚点；同一页、同文本、同坐标和句内序号得到同一值。
        /// </summary>
        public static string BuildAnchorKey(PdfHighlight highlight, int partIndex)
        {
            string normalized = NormalizeKey(highlight.Text);
            string raw = string.Join("|", new[]
            {
                highlight.PageIndex.ToString(),
                normalized,
                Math.Round(highlight.NormalizedY, 3).ToString("0.###"),
                Math.Round(highlight.NormalizedX, 3).ToString("0.###"),
                partIndex.ToString()
            });
            string hash = Convert.ToHexString(
                SHA256.HashData(Encoding.UTF8.GetBytes(raw)))[..16].ToLowerInvariant();
            return $"hl:{highlight.PageIndex}:{hash}:{partIndex}";
        }

        private static PdfHighlight? FindBestHighlight(string sentenceText, IReadOnlyList<PdfHighlight> highlights)
        {
            string target = NormalizeKey(sentenceText);
            if (target.Length == 0)
                return null;

            var targetTokens = Tokenize(target);
            PdfHighlight? best = null;
            double bestScore = 0;

            foreach (var highlight in highlights)
            {
                string candidate = NormalizeKey(highlight.Text);
                if (candidate.Length == 0)
                    continue;

                double score;
                if (string.Equals(candidate, target, StringComparison.Ordinal))
                {
                    score = 1.0;
                }
                else if (candidate.Contains(target, StringComparison.Ordinal))
                {
                    // 高亮是段落时优先选择包含该句且长度最接近的高亮
                    score = 0.85 + Math.Min(0.1, 100.0 / Math.Max(1, candidate.Length));
                }
                else if (target.Contains(candidate, StringComparison.Ordinal) && candidate.Length >= 8)
                {
                    score = 0.8;
                }
                else
                {
                    var candidateTokens = Tokenize(candidate);
                    if (targetTokens.Count == 0 || candidateTokens.Count == 0)
                        continue;

                    int intersection = targetTokens.Count(candidateTokens.Contains);
                    int union = targetTokens.Count + candidateTokens.Count - intersection;
                    double overlap = union == 0 ? 0 : intersection / (double)union;
                    if (overlap < 0.6)
                        continue;

                    score = 0.5 + overlap * 0.3;
                }

                // 同分时手动高亮优先于自动高亮
                if (highlight.IsAutoGenerated)
                    score -= 0.05;

                if (score > bestScore)
                {
                    bestScore = score;
                    best = highlight;
                }
            }

            return bestScore >= 0.6 ? best : null;
        }

        private static List<string> SplitText(string text)
            => SentenceSegmenter.Segment(text)
                .Select(sentence => sentence.Text)
                .Where(part => !string.IsNullOrWhiteSpace(part))
                .ToList();

        private static bool IsDuplicateAutoHighlight(
            PdfHighlight highlight,
            IReadOnlyList<PdfHighlight> manualHighlights)
        {
            if (!highlight.IsAutoGenerated)
                return false;

            foreach (var manual in manualHighlights)
            {
                if (manual.PageIndex != highlight.PageIndex)
                    continue;
                if (OverlapRatio(highlight, manual) >= 0.6)
                    return true;
            }

            return false;
        }

        private static double OverlapRatio(PdfHighlight auto, PdfHighlight manual)
        {
            float left = Math.Max(auto.NormalizedX, manual.NormalizedX);
            float top = Math.Max(auto.NormalizedY, manual.NormalizedY);
            float right = Math.Min(auto.NormalizedX + auto.NormalizedWidth, manual.NormalizedX + manual.NormalizedWidth);
            float bottom = Math.Min(auto.NormalizedY + auto.NormalizedHeight, manual.NormalizedY + manual.NormalizedHeight);
            if (right <= left || bottom <= top)
                return 0;

            double intersection = (right - left) * (bottom - top);
            double autoArea = Math.Max(1e-6, auto.NormalizedWidth * auto.NormalizedHeight);
            return intersection / autoArea;
        }

        private static HashSet<string> Tokenize(string text)
        {
            var tokens = new HashSet<string>(StringComparer.Ordinal);
            foreach (string token in TokenSeparator.Split(text))
            {
                if (token.Length > 0)
                    tokens.Add(token);
            }

            return tokens;
        }

        private static int CountLetters(string text)
        {
            int count = 0;
            foreach (char ch in text)
            {
                if (char.IsLetter(ch))
                    count++;
            }

            return count;
        }

        // 与锚点生成共用同一规范化口径（ShadowingAnchorKeys.NormalizeKey），避免匹配与锚点漂移
        private static string NormalizeKey(string? text)
            => ShadowingAnchorKeys.NormalizeKey(text);

        private static string NormalizeText(string? text)
        {
            if (string.IsNullOrWhiteSpace(text))
                return string.Empty;

            var builder = new StringBuilder(text.Length);
            bool pendingSpace = false;
            foreach (char ch in text.Trim())
            {
                if (char.IsWhiteSpace(ch))
                {
                    pendingSpace = builder.Length > 0;
                    continue;
                }

                if (pendingSpace)
                {
                    builder.Append(' ');
                    pendingSpace = false;
                }

                builder.Append(ch);
            }

            return builder.ToString();
        }
    }
