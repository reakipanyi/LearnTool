using LearningAssistant.Models.Pdf;
using LearningAssistant.Services.Shadowing;
using Xunit;

namespace LearningAssistant.Core.Tests;

public class ShadowingHighlightSourceTests
{
    [Fact]
    public void Build_OrdersByPageThenVerticalPosition()
    {
        var highlights = new[]
        {
            Highlight("page2-lower", page: 2, y: 0.6f, x: 0.1f, text: "Page two lower."),
            Highlight("page1-lower", page: 1, y: 0.5f, x: 0.1f, text: "Page one lower."),
            Highlight("page1-upper", page: 1, y: 0.2f, x: 0.4f, text: "Page one upper."),
            Highlight("page1-left", page: 1, y: 0.2f, x: 0.1f, text: "Page one left.")
        };

        var plan = ShadowingHighlightSource.Build(highlights);

        Assert.Equal(
            new[] { "Page one left.", "Page one upper.", "Page one lower.", "Page two lower." },
            plan.Sentences.Select(s => s.Sentence.Text));
        Assert.Equal(new[] { 1, 1, 1, 2 }, plan.Sentences.Select(s => s.PageIndex));
    }

    [Fact]
    public void Build_SkipsEmptyTextAndCountsSkippedHighlights()
    {
        var highlights = new[]
        {
            Highlight("empty", page: 0, y: 0.1f, text: "   "),
            Highlight("valid", page: 0, y: 0.2f, text: "Keep me."),
            Highlight("null-text", page: 0, y: 0.3f, text: null)
        };

        var plan = ShadowingHighlightSource.Build(highlights);

        Assert.Single(plan.Sentences);
        Assert.Equal("Keep me.", plan.Sentences[0].Sentence.Text);
        Assert.Equal(2, plan.SkippedCount);
    }

    [Fact]
    public void Build_NormalizesWhitespaceAndUsesStablePrefixedIds()
    {
        var highlight = Highlight("stable-id", page: 3, y: 0.1f, text: "  Hello \r\n world  ");

        var plan = ShadowingHighlightSource.Build(new[] { highlight, highlight });

        Assert.Single(plan.Sentences);
        Assert.Equal("Hello world", plan.Sentences[0].Sentence.Text);
        Assert.Equal(ShadowingHighlightSource.SentenceIdPrefix + "stable-id", plan.Sentences[0].Sentence.Id);
        Assert.Equal(0, plan.Sentences[0].Sentence.Index);
        Assert.Equal("Hello world".Length, plan.Sentences[0].Sentence.Length);
    }

    [Fact]
    public void Build_SplitIntoSentences_CreatesStablePartIdsAndAnchors()
    {
        var highlight = Highlight(
            "auto-1", page: 4, y: 0.2f,
            text: "First sentence is here. Second sentence is here! Third sentence is here?");

        var plan = ShadowingHighlightSource.Build(new[] { highlight }, splitIntoSentences: true);

        Assert.Equal(3, plan.Sentences.Count);
        Assert.Equal(
            new[] { "hl:auto-1:0", "hl:auto-1:1", "hl:auto-1:2" },
            plan.Sentences.Select(s => s.Sentence.Id));
        Assert.Equal(new[] { 0, 1, 2 }, plan.Sentences.Select(s => s.PartIndex));
        Assert.All(plan.Sentences, s => Assert.StartsWith("hl:4:", s.AnchorKey));
        Assert.All(plan.Sentences, s => Assert.Equal("auto-1", s.HighlightId));
    }

    [Fact]
    public void Build_SkipsAutoBlockCoveredByManualHighlight()
    {
        var manual = Highlight(
            "manual", page: 1, y: 0.2f,
            text: "A manually highlighted paragraph.");
        var auto = Highlight(
            "auto", page: 1, y: 0.2f,
            text: "A manually highlighted paragraph.");
        auto.IsAutoGenerated = true;

        var plan = ShadowingHighlightSource.Build(new[] { auto, manual });

        Assert.Single(plan.Sentences);
        Assert.Equal("manual", plan.Sentences[0].HighlightId);
        Assert.Equal(1, plan.SkippedCount);
    }

    [Fact]
    public void BuildAnchorKey_IgnoresHighlightIdSoAutoRegenerationKeepsAnchor()
    {
        var original = Highlight(
            "auto-old", page: 7, y: 0.33f, x: 0.21f,
            text: "Same paragraph text.");
        original.IsAutoGenerated = true;
        var regenerated = Highlight(
            "auto-new", page: 7, y: 0.33f, x: 0.21f,
            text: "Same paragraph text.");
        regenerated.IsAutoGenerated = true;

        Assert.Equal(
            ShadowingHighlightSource.BuildAnchorKey(original, 0),
            ShadowingHighlightSource.BuildAnchorKey(regenerated, 0));
    }

    [Fact]
    public void BuildPageCues_MatchesPageSentencesAndKeepsOneCuePerSentence()
    {
        var sentences = SentenceSegmenter.Segment(
            "The first sentence is highlighted. An unmatched sentence follows.");
        var highlight = Highlight(
            "manual", page: 2, y: 0.1f,
            text: "The first sentence is highlighted.");

        var cues = ShadowingHighlightSource.BuildPageCues(sentences, new[] { highlight }, pageIndex: 2);

        Assert.Equal(sentences.Count, cues.Count);
        Assert.Equal("manual", cues[0].HighlightId);
        Assert.Equal("highlight", cues[0].TextSource);
        Assert.Contains("hl:2:", cues[0].AnchorKey);
        Assert.Null(cues[1].HighlightId);
        Assert.StartsWith("txt:2:", cues[1].AnchorKey);
        Assert.Equal(sentences[1].Id, cues[1].SentenceId);
    }

    [Fact]
    public void BuildPageCues_SkipsAutoHighlightCoveredByManualHighlight()
    {
        var sentences = SentenceSegmenter.Segment("The matched sentence is here.");
        var manual = Highlight(
            "manual", page: 3, y: 0.1f,
            text: "The matched sentence is here.");
        var auto = Highlight(
            "auto", page: 3, y: 0.1f,
            text: "The matched sentence is here.");
        auto.IsAutoGenerated = true;

        var cues = ShadowingHighlightSource.BuildPageCues(sentences, new[] { auto, manual }, pageIndex: 3);

        var cue = Assert.Single(cues);
        Assert.Equal("manual", cue.HighlightId);
        Assert.Equal("highlight", cue.TextSource);
        Assert.StartsWith(
            ShadowingHighlightSource.BuildAnchorKey(manual, 0) + "|",
            cue.AnchorKey);
    }

    [Fact]
    public void BuildPageCues_NoHighlights_StillReturnsTextAnchors()
    {
        var sentences = SentenceSegmenter.Segment("Only page text.");

        var cues = ShadowingHighlightSource.BuildPageCues(sentences, null, pageIndex: 9);

        var cue = Assert.Single(cues);
        Assert.Equal("page-text", cue.TextSource);
        Assert.Equal($"txt:9:{sentences[0].Id}", cue.AnchorKey);
    }

    private static PdfHighlight Highlight(string id, int page, float y, string? text, float x = 0.1f)
    {
        return new PdfHighlight
        {
            Id = id,
            PageIndex = page,
            NormalizedX = x,
            NormalizedY = y,
            NormalizedWidth = 0.5f,
            NormalizedHeight = 0.05f,
            Text = text ?? string.Empty,
            CreatedAt = new DateTime(2026, 1, 1)
        };
    }
}
